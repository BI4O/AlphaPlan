#!/usr/bin/env node
/**
 * 从 Foundry 产物生成 `lib/abi/alphaPlanVault.ts`。
 *
 * 为什么不直接 import `src/contract/out/.../AlphaPlanVault.json`：
 *   1. `out/` 在 .gitignore 里，干净检出时不存在 —— 运行时跨目录依赖会当场炸；
 *   2. 前端不该知道合约仓库的目录布局，部署时两份目录也未必在同一相对位置。
 * 所以产物入库，本脚本只负责在合约重新编译后把它刷新。
 *
 * 因为产物入库，脚本是 **best-effort**：找不到产物就保留旧文件并警告，不阻断构建
 * （Docker / CI 里没有 forge 的机器仍然能 `pnpm build`）。
 *
 * 用法：
 *   node scripts/gen-abi.mjs              # 有产物就刷新，没有就警告
 *   node scripts/gen-abi.mjs --check      # 只检查是否落后，落后则退出 1
 *   CONTRACT_ARTIFACT=/path/to.json node scripts/gen-abi.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const artifactPath =
  process.env.CONTRACT_ARTIFACT ??
  path.resolve(projectRoot, "../../contract/out/AlphaPlanVault.sol/AlphaPlanVault.json");
const outputPath = path.resolve(projectRoot, "lib/abi/alphaPlanVault.ts");
const checkOnly = process.argv.includes("--check");

function fail(message) {
  console.error(`gen-abi: ${message}`);
  process.exit(1);
}

function warn(message) {
  console.warn(`gen-abi: ${message}`);
}

// 落在项目外的路径，path.relative 会输出一串 ../../，直接给绝对路径更好读。
const displayedArtifact = artifactPath.startsWith(projectRoot)
  ? path.relative(projectRoot, artifactPath)
  : artifactPath;

if (!fs.existsSync(artifactPath)) {
  const hint =
    `找不到合约产物 ${displayedArtifact}\n` +
    `  刷新它：cd src/contract && forge build\n` +
    `  或指定路径：CONTRACT_ARTIFACT=/path/to/AlphaPlanVault.json node scripts/gen-abi.mjs`;

  if (checkOnly) fail(`产物缺失且要求 --check。\n${hint}`);
  if (fs.existsSync(outputPath)) {
    warn(`产物缺失，保留已有 ${path.relative(projectRoot, outputPath)}（未刷新）。\n${hint}`);
    process.exit(0);
  }
  fail(`产物缺失且没有已入库的 ABI 可用。\n${hint}`);
}

let artifact;
try {
  artifact = JSON.parse(fs.readFileSync(artifactPath, "utf8"));
} catch (error) {
  fail(`读不动 ${artifactPath}：${error.message}`);
}

const abi = artifact.abi;
if (!Array.isArray(abi) || abi.length === 0) {
  fail(`${artifactPath} 里没有 abi 数组（forge build 是否完成？）`);
}

// 事件签名是我们最关心的契约：E4 ②③ 依赖 PlanExecuted 带 asOf/validUntil。
// 缺了就在生成时喊出来，而不是等前端渲染成 undefined。
const executed = abi.find((item) => item.type === "event" && item.name === "PlanExecuted");
const executedInputs = (executed?.inputs ?? []).map((input) => input.name);
const missing = ["asOf", "validUntil"].filter((name) => !executedInputs.includes(name));

const generated = `// @generated by scripts/gen-abi.mjs — 不要手改。
// 源头：src/contract/out/AlphaPlanVault.sol/AlphaPlanVault.json
// 刷新：cd src/frontend/alpha-plan && pnpm gen:abi
export const alphaPlanVaultAbi = ${JSON.stringify(abi, null, 2)} as const;

/** PlanExecuted / PlanRecorded 的事件入参名，供前端断言字段齐备。 */
export const planEventFieldNames = ${JSON.stringify(executedInputs)} as const;
`;

if (checkOnly) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : "";
  if (current !== generated) fail("lib/abi/alphaPlanVault.ts 落后于合约产物，跑 pnpm gen:abi");
  console.log("gen-abi: ABI 与合约产物一致");
  process.exit(0);
}

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, generated);
console.log(
  `gen-abi: 写入 ${path.relative(projectRoot, outputPath)}（${abi.length} 个 ABI 项，` +
    `PlanExecuted 字段 ${executedInputs.length} 个）`,
);

if (missing.length > 0) {
  warn(
    `PlanExecuted 缺少 ${missing.join(", ")} —— E4 ②③ 无法从事件取值。` +
      `合约改完后重跑本脚本。`,
  );
}
