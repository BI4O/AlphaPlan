/**
 * 界面术语表 —— 一个术语，一处定义。
 *
 * ## 为什么需要它
 *
 * 给人看的界面（尤其是给评委看的）不该假设读者知道 `bps` 是什么。
 * 但也不能每处都塞一句解释，那会把界面变成说明书。
 *
 * 所以分两层：
 *   · **界面上的主标签**用能直接看懂的说法（「风险资产占比」而不是「仓位 bps」）
 *   · **术语首次出现或数字旁边**给一句短注释，鼠标悬停能看到完整定义
 *
 * ## 规矩
 *
 * 1. 释义必须**能给外行讲明白**，不靠术语解释术语。
 * 2. 释义里的数字必须是这家金库的真实约束（6000 上限、300 容差），
 *    不是「大约」「通常是」—— 那些是没法验证的措辞。
 * 3. 一个术语只在这里定义一次。界面上要用就 import，
 *    不要在 JSX 里再写一遍 —— 两处写就会两处不一致。
 */

